package com.animecore.client.render;

import com.animecore.entity.StoryNpcEntity;
import com.animecore.platform.Ids;
import com.animecore.quest.StoryNpcDefinition;
import net.minecraft.client.render.OverlayTexture;
import net.minecraft.client.render.RenderLayer;
import net.minecraft.client.render.VertexConsumerProvider;
import net.minecraft.client.render.entity.EntityRendererFactory;
import net.minecraft.client.render.entity.LivingEntityRenderer;
import net.minecraft.client.render.entity.feature.FeatureRenderer;
import net.minecraft.client.render.entity.feature.FeatureRendererContext;
import net.minecraft.client.render.entity.feature.HeldItemFeatureRenderer;
import net.minecraft.client.render.entity.model.EntityModelLayers;
import net.minecraft.client.render.entity.model.PlayerEntityModel;
import net.minecraft.client.util.math.MatrixStack;
import net.minecraft.util.Identifier;

import java.util.Set;

/**
 * Story characters: the vanilla player model drawn once per appearance layer (skin, face, eyes, pants, outfit + accent,
 * hair, headband, face mark), each tinted with the colour from the character's {@link StoryNpcDefinition.Appearance}.
 * The layer textures are shared grayscale sheets generated by {@code tools/catalog/npc_skins.py}.
 */
public class StoryNpcRenderer extends LivingEntityRenderer<StoryNpcEntity, PlayerEntityModel<StoryNpcEntity>> {
    private static final Identifier EMPTY = tex("empty");
    private static final Set<String> OUTFITS = Set.of("shirt", "jacket", "cloak", "robe", "bodysuit", "armor");
    private static final Set<String> HAIR = Set.of("short", "spiky", "long", "ponytail", "bowl", "buns", "wild", "bald");
    private static final Set<String> MARKS = Set.of("whiskers", "fangs", "forehead", "red_eyes", "pale_eyes", "rinnegan", "mask",
            "paint", "scar", "forehead_kanji", "glasses");

    public StoryNpcRenderer(EntityRendererFactory.Context ctx) {
        super(ctx, new PlayerEntityModel<>(ctx.getPart(EntityModelLayers.PLAYER), false), 0.5f);
        addFeature(new Layers(this));
        addFeature(new HeldItemFeatureRenderer<>(this, ctx.getHeldItemRenderer()));
    }

    /** Characters with a low-poly model (tailed beasts) are drawn as that model; everyone else as a tinted humanoid. */
    @Override
    public void render(StoryNpcEntity entity, float yaw, float tickDelta, MatrixStack matrices, VertexConsumerProvider buffers, int light) {
        var model = entity.definition().flatMap(d -> d.appearance().model()).map(FormModels::get).orElse(null);
        if (model == null) {
            super.render(entity, yaw, tickDelta, matrices, buffers, light);
            return;
        }
        FormModelRenderer.render(entity, model, tickDelta, matrices, buffers, light);
        if (hasLabel(entity)) renderLabelIfPresent(entity, entity.getDisplayName(), matrices, buffers, light, tickDelta);
    }

    static Identifier tex(String name) { return Ids.core("textures/entity/story_npc/" + name + ".png"); }

    @Override
    public Identifier getTexture(StoryNpcEntity entity) { return EMPTY; }

    @Override
    protected RenderLayer getRenderLayer(StoryNpcEntity entity, boolean showBody, boolean translucent, boolean showOutline) {
        return RenderLayer.getEntityCutoutNoCull(EMPTY);
    }

    private static final class Layers extends FeatureRenderer<StoryNpcEntity, PlayerEntityModel<StoryNpcEntity>> {
        Layers(FeatureRendererContext<StoryNpcEntity, PlayerEntityModel<StoryNpcEntity>> ctx) { super(ctx); }

        @Override
        public void render(MatrixStack matrices, VertexConsumerProvider buffers, int light, StoryNpcEntity entity,
                           float limbAngle, float limbDistance, float tickDelta, float animationProgress, float headYaw, float headPitch) {
            StoryNpcDefinition.Appearance a = entity.definition().map(StoryNpcDefinition::appearance).orElse(StoryNpcDefinition.Appearance.DEFAULT);
            int overlay = LivingEntityRenderer.getOverlay(entity, 0f);
            draw(matrices, buffers, light, overlay, "skin", a.skin());
            draw(matrices, buffers, light, overlay, "face", 0xFFFFFF);
            draw(matrices, buffers, light, overlay, "eyes", a.eyes());
            draw(matrices, buffers, light, overlay, "pants", a.pants());
            String outfit = OUTFITS.contains(a.outfit()) ? a.outfit() : "shirt";
            draw(matrices, buffers, light, overlay, "outfit_" + outfit, a.top());
            draw(matrices, buffers, light, overlay, "outfit_" + outfit + "_accent", a.accent());
            String hair = HAIR.contains(a.hairStyle()) ? a.hairStyle() : "short";
            if (!hair.equals("bald")) draw(matrices, buffers, light, overlay, "hair_" + hair, a.hair());
            a.headband().ifPresent(c -> {
                draw(matrices, buffers, light, overlay, "headband", c);
                draw(matrices, buffers, light, overlay, "headband_plate", 0xFFFFFF);
            });
            a.mark().filter(MARKS::contains).ifPresent(m -> draw(matrices, buffers, light, overlay, "mark_" + m, 0xFFFFFF));
        }

        private void draw(MatrixStack matrices, VertexConsumerProvider buffers, int light, int overlay, String layer, int rgb) {
            getContextModel().render(matrices, buffers.getBuffer(RenderLayer.getEntityCutoutNoCull(tex(layer))), light, overlay,
                    0xFF000000 | (rgb & 0xFFFFFF));
        }
    }
}
