package com.jojorpg.content;

import com.animecore.clan.ClanConfig;
import com.animecore.clan.ClanRollService;
import com.animecore.item.AdminSealItem;
import com.animecore.item.AwakeningItem;
import com.animecore.item.ClanEmblemItem;
import com.animecore.item.LineageAwakeningItem;
import com.animecore.item.ManifestationItem;
import com.animecore.item.QuestScrollItem;
import com.animecore.technique.TechniqueTokenItem;
import com.animecore.technique.TechniqueTokens;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.jojorpg.JojoRPG;
import net.fabricmc.fabric.api.itemgroup.v1.FabricItemGroup;
import net.fabricmc.fabric.api.networking.v1.ServerPlayConnectionEvents;
import net.minecraft.item.Item;
import net.minecraft.item.ItemGroup;
import net.minecraft.item.ItemStack;
import net.minecraft.registry.Registries;
import net.minecraft.registry.Registry;
import net.minecraft.text.Text;
import net.minecraft.util.Formatting;
import net.minecraft.util.Identifier;
import net.minecraft.util.Rarity;

import java.io.InputStreamReader;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Everything a JoJo player holds: technique items (Ripple, Vampire, Pillar Men, German Science, Martial Arts, Modes),
 * the Style Manual (fighting-style mastery), the Quest Scroll, admin seals and the awakening items generated by
 * tools/catalog/jojo_content.py (Breathing Mask, Stone Mask, Red Stone of Aja...).
 */
public final class JojoItems {
    private JojoItems() {}

    /** token id path -> (display name, colour) */
    public static final String[][] TOKENS = {
            {"ripple", "Ripple (Hamon)", "FFD54F"}, {"vampire", "Vampirism", "B71C1C"}, {"pillar_men", "Pillar Men Arts", "8D6E63"},
            {"science", "German Science", "90A4AE"}, {"martial", "Martial Arts", "FF8A65"}, {"modes", "Modes", "E1BEE7"},
            {"stand", "Stand", "B39DDB"},
    };
    public static final Map<Identifier, Item> TOKEN_ITEMS = new LinkedHashMap<>();
    public static final Map<String, Item> AWAKENING = new LinkedHashMap<>();
    /** Stand Arrow + one Stand Disc per Part 3 Stand (assets/jojorpg/jojo_stand_items.json, from jojo_stands.py). */
    public static final Map<String, Item> STAND_ITEMS = new LinkedHashMap<>();
    public static final Map<AdminSealItem.Action, Item> SEALS = new LinkedHashMap<>();
    public static final String GIVEN_TAG = "jojorpg.quest_scroll";

    public static final Item STYLE_MANUAL;
    public static final Item QUEST_SCROLL;

    static {
        for (String[] t : TOKENS) {
            Identifier token = JojoRPG.CTX.id(t[0]);
            TOKEN_ITEMS.put(token, Registry.register(Registries.ITEM, JojoRPG.CTX.id(t[0] + "_arts"),
                    new TechniqueTokenItem(JojoRPG.CTX, token, Integer.parseInt(t[2], 16), new Item.Settings().rarity(Rarity.UNCOMMON))));
        }
        TechniqueTokens.configure(JojoRPG.CTX, TOKEN_ITEMS, JojoRPG.CTX.id("martial"), JojoRPG.CTX.id("modes"));
        STYLE_MANUAL = Registry.register(Registries.ITEM, JojoRPG.CTX.id("style_manual"), new ClanEmblemItem(JojoRPG.CTX, new Item.Settings()));
        // fighting styles are learned (masks, training, science), never rolled
        ClanRollService.configure(JojoRPG.CTX, new ClanConfig(() -> STYLE_MANUAL, null, 0, 0, false, false));
        QUEST_SCROLL = Registry.register(Registries.ITEM, JojoRPG.CTX.id("quest_scroll"),
                new QuestScrollItem(JojoRPG.CTX, new Item.Settings().rarity(Rarity.UNCOMMON)));
        for (AdminSealItem.Action a : AdminSealItem.Action.values()) {
            SEALS.put(a, Registry.register(Registries.ITEM, JojoRPG.CTX.id("admin_seal_" + a.key()),
                    new AdminSealItem(JojoRPG.CTX, a, new Item.Settings())));
        }
        try (Reader r = new InputStreamReader(JojoItems.class.getResourceAsStream("/assets/jojorpg/jojo_items.json"), StandardCharsets.UTF_8)) {
            for (JsonElement e : JsonParser.parseReader(r).getAsJsonArray()) {
                JsonObject o = e.getAsJsonObject();
                String id = o.get("item").getAsString();
                Identifier target = Identifier.of(o.get("target").getAsString());
                String lore = o.get("lore").getAsString();
                Item.Settings settings = new Item.Settings().rarity(Rarity.EPIC);
                Item item = "lineage".equals(o.get("kind").getAsString())
                        ? new LineageAwakeningItem(JojoRPG.CTX, target, lore, false, settings)
                        : new AwakeningItem(JojoRPG.CTX, target, lore, settings);
                AWAKENING.put(id, Registry.register(Registries.ITEM, JojoRPG.CTX.id(id), item));
            }
        } catch (Exception ex) {
            throw new IllegalStateException("assets/jojorpg/jojo_items.json missing - run python3 tools/catalog/jojo_content.py", ex);
        }
        try (Reader r = new InputStreamReader(JojoItems.class.getResourceAsStream("/assets/jojorpg/jojo_stand_items.json"), StandardCharsets.UTF_8)) {
            for (JsonElement e : JsonParser.parseReader(r).getAsJsonArray()) {
                JsonObject o = e.getAsJsonObject();
                String id = o.get("item").getAsString();
                boolean arrow = "arrow".equals(o.get("kind").getAsString());
                Identifier target = arrow ? null : Identifier.of(o.get("target").getAsString());
                Item item = new ManifestationItem(JojoRPG.CTX, target, o.get("lore").getAsString(), arrow ? 6f : 0f,
                        new Item.Settings().rarity(arrow ? Rarity.EPIC : Rarity.RARE));
                STAND_ITEMS.put(id, Registry.register(Registries.ITEM, JojoRPG.CTX.id(id), item));
            }
        } catch (Exception ex) {
            throw new IllegalStateException("assets/jojorpg/jojo_stand_items.json missing - run python3 tools/catalog/jojo_stands.py", ex);
        }
    }

    public static final ItemGroup GROUP = Registry.register(Registries.ITEM_GROUP, JojoRPG.CTX.id("main"),
            FabricItemGroup.builder()
                    .icon(() -> new ItemStack(AWAKENING.getOrDefault("stone_mask", QUEST_SCROLL)))
                    .displayName(Text.translatable("itemGroup.jojorpg"))
                    .entries((ctx, entries) -> {
                        entries.add(QUEST_SCROLL);
                        entries.add(STYLE_MANUAL);
                        AWAKENING.values().forEach(entries::add);
                        TOKEN_ITEMS.values().forEach(entries::add);
                        entries.add(STAND_ITEMS.get("stand_arrow"));
                    }).build());

    public static final ItemGroup STANDS_GROUP = Registry.register(Registries.ITEM_GROUP, JojoRPG.CTX.id("stands"),
            FabricItemGroup.builder()
                    .icon(() -> new ItemStack(STAND_ITEMS.getOrDefault("disc_star_platinum", QUEST_SCROLL)))
                    .displayName(Text.translatable("itemGroup.jojorpg.stands"))
                    .entries((ctx, entries) -> STAND_ITEMS.values().forEach(entries::add)).build());

    public static final ItemGroup ADMIN_GROUP = Registry.register(Registries.ITEM_GROUP, JojoRPG.CTX.id("admin"),
            FabricItemGroup.builder()
                    .icon(() -> new ItemStack(SEALS.get(AdminSealItem.Action.MAX_ALL)))
                    .displayName(Text.translatable("itemGroup.jojorpg.admin"))
                    .entries((ctx, entries) -> SEALS.values().forEach(entries::add)).build());

    public static Item awakening(String id) { return AWAKENING.get(id); }
    public static Item standItem(String id) { return STAND_ITEMS.get(id); }

    public static void init() {
        ServerPlayConnectionEvents.JOIN.register((handler, sender, server) -> {
            var player = handler.player;
            if (player.getCommandTags().contains(GIVEN_TAG)) return;
            player.addCommandTag(GIVEN_TAG);
            if (!player.getInventory().insertStack(new ItemStack(QUEST_SCROLL))) player.dropItem(new ItemStack(QUEST_SCROLL), false);
            player.sendMessage(Text.translatable("message.jojorpg.quest_scroll").formatted(Formatting.GOLD), false);
        });
    }
}
