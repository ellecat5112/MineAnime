package com.narutorpg.content;

import com.animecore.registry.AnimeRegistries;
import com.animecore.registry.definition.AbilityDefinition;
import com.animecore.registry.definition.AffinityDefinition;
import com.animecore.registry.definition.FactionDefinition;
import com.animecore.registry.definition.LineageDefinition;
import com.animecore.registry.definition.TransformationDefinition;
import com.narutorpg.NarutoRPG;
import net.minecraft.registry.Registry;
import net.minecraft.registry.RegistryKey;
import net.minecraft.util.Identifier;

/** Registry keys for NarutoRPG content (values live in JSON, generated by {@code NarutoContentBootstrap}). */
public final class NarutoContent {
    private NarutoContent() {}

    // Pools
    public static final Identifier CHAKRA = NarutoRPG.CTX.id("chakra");
    public static final Identifier STAMINA = NarutoRPG.CTX.id("stamina");

    // Nature releases
    public static final RegistryKey<AffinityDefinition> FIRE = key(AnimeRegistries.AFFINITY, "fire");
    public static final RegistryKey<AffinityDefinition> WIND = key(AnimeRegistries.AFFINITY, "wind");
    public static final RegistryKey<AffinityDefinition> LIGHTNING = key(AnimeRegistries.AFFINITY, "lightning");
    public static final RegistryKey<AffinityDefinition> EARTH = key(AnimeRegistries.AFFINITY, "earth");
    public static final RegistryKey<AffinityDefinition> WATER = key(AnimeRegistries.AFFINITY, "water");

    // Clans & villages
    public static final RegistryKey<LineageDefinition> UCHIHA = key(AnimeRegistries.LINEAGE, "uchiha");
    public static final RegistryKey<FactionDefinition> HIDDEN_LEAF = key(AnimeRegistries.FACTION, "hidden_leaf");

    // Jutsu
    public static final RegistryKey<AbilityDefinition> FIREBALL_JUTSU = key(AnimeRegistries.ABILITY, "fireball_jutsu");
    public static final RegistryKey<AbilityDefinition> SUBSTITUTION_JUTSU = key(AnimeRegistries.ABILITY, "substitution_jutsu");

    // Dojutsu
    public static final RegistryKey<TransformationDefinition> SHARINGAN_1 = key(AnimeRegistries.TRANSFORMATION, "sharingan_one_tomoe");
    public static final RegistryKey<TransformationDefinition> SHARINGAN_2 = key(AnimeRegistries.TRANSFORMATION, "sharingan_two_tomoe");
    public static final RegistryKey<TransformationDefinition> SHARINGAN_3 = key(AnimeRegistries.TRANSFORMATION, "sharingan_three_tomoe");
    public static final RegistryKey<TransformationDefinition> MANGEKYO = key(AnimeRegistries.TRANSFORMATION, "mangekyo_sharingan");

    private static <T> RegistryKey<T> key(RegistryKey<? extends Registry<T>> registry, String path) {
        return RegistryKey.of(registry, NarutoRPG.CTX.id(path));
    }
}
