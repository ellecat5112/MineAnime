package com.narutorpg.content;

import com.animecore.tool.NinjaArmorItem;
import com.animecore.tool.NinjaToolItem;
import com.animecore.tool.ToolSpec;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonParser;
import com.mojang.serialization.JsonOps;
import com.narutorpg.NarutoRPG;
import net.fabricmc.fabric.api.itemgroup.v1.FabricItemGroup;
import net.minecraft.item.Item;
import net.minecraft.item.ItemGroup;
import net.minecraft.item.ItemStack;
import net.minecraft.registry.Registries;
import net.minecraft.registry.Registry;
import net.minecraft.text.Text;

import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Every ninja tool from Narutopedia's Category:Tools, registered from {@code assets/narutorpg/ninja_tools.json}
 * (generated by {@code tools/catalog/build.py}). One creative tab per wiki "Tool classification" group.
 */
public final class NarutoTools {
    private NarutoTools() {}

    public static final String CATALOG = "/assets/narutorpg/ninja_tools.json";
    public static final List<String> GROUPS = List.of("Offensive", "Defensive", "Supplementary", "Unclassified", "Generic");

    private static final Map<String, ToolSpec> SPECS = new LinkedHashMap<>();
    private static final Map<String, Item> ITEMS = new LinkedHashMap<>();

    static {
        for (JsonElement el : readCatalog()) {
            ToolSpec spec = ToolSpec.CODEC.parse(JsonOps.INSTANCE, el).getOrThrow(msg -> new IllegalStateException("Bad tool " + el + ": " + msg));
            SPECS.put(spec.id(), spec);
            boolean existing = el.getAsJsonObject().has("existing") && el.getAsJsonObject().get("existing").getAsBoolean();
            if (existing) continue;
            Item item = spec.armor().isPresent() ? new NinjaArmorItem(spec, NarutoRPG.CTX) : new NinjaToolItem(spec, NarutoRPG.CTX);
            ITEMS.put(spec.id(), Registry.register(Registries.ITEM, NarutoRPG.CTX.id(spec.id()), item));
        }
        for (String group : GROUPS) {
            Registry.register(Registries.ITEM_GROUP, NarutoRPG.CTX.id("tools_" + group.toLowerCase()), FabricItemGroup.builder()
                    .icon(() -> new ItemStack(icon(group)))
                    .displayName(Text.translatable("itemGroup.narutorpg.tools_" + group.toLowerCase()))
                    .entries((ctx, entries) -> {
                        for (Map.Entry<String, ToolSpec> e : SPECS.entrySet()) {
                            if (!e.getValue().classification().contains(group)) continue;
                            Item item = ITEMS.get(e.getKey());
                            if (item == null) item = Registries.ITEM.get(NarutoRPG.CTX.id(e.getKey()));
                            entries.add(item);
                        }
                    }).build());
        }
    }

    private static Item icon(String group) {
        String id = switch (group) {
            case "Offensive" -> "shuriken";
            case "Defensive" -> "barrier_tag";
            case "Supplementary" -> "military_rations_pill";
            case "Unclassified" -> "kunai";
            default -> "bo";
        };
        return ITEMS.getOrDefault(id, net.minecraft.item.Items.PAPER);
    }

    private static JsonArray readCatalog() {
        try (InputStream in = NarutoTools.class.getResourceAsStream(CATALOG)) {
            if (in == null) throw new IllegalStateException("Missing " + CATALOG);
            return JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonArray();
        } catch (java.io.IOException e) {
            throw new IllegalStateException(e);
        }
    }

    public static Item item(String id) {
        Item item = ITEMS.get(id);
        if (item == null) throw new IllegalArgumentException("Unknown ninja tool " + id);
        return item;
    }

    public static Map<String, Item> items() { return Collections.unmodifiableMap(ITEMS); }
    public static Map<String, ToolSpec> specs() { return Collections.unmodifiableMap(SPECS); }

    public static List<String> ids() { return new ArrayList<>(SPECS.keySet()); }

    public static void init() {}
}
